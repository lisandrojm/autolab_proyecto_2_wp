import mongoose from "mongoose";
import { Tenant } from "../models/Tenant.js";
import { User } from "../models/User.js";
import UserProject from "../models/UserProject.js";
import { rangoDelMes } from "../utils/planillaJornaleros.js";
await mongoose.connect(process.env.MONGO_URI!, { dbName: process.env.MONGO_DB_NAME });
const t: any = await Tenant.findOne({ slug: "demo-tenant" }).lean();
const { desde, hasta } = rangoDelMes("2026-10");
let t0 = Date.now();
const f = { tenantId: t._id, "metadata.solicitudStatus": "aprobada", "metadata.startDate": { $gte: desde, $lte: hasta } };
const s: any[] = await User.find(f, { firstName: 1, lastName: 1, metadata: 1 }).lean();
console.log("solicitudes", s.length, Date.now() - t0, "ms", JSON.stringify(s).length, "bytes");
console.log(JSON.stringify(await User.find(f).explain("executionStats")).match(/"totalDocsExamined":\d+|"executionTimeMillis":\d+|"stage":"IXSCAN"|"indexName":"[^"]+"/g));
t0 = Date.now();
const ids = s.map((x) => x._id);
const ups: any[] = await UserProject.find({ "contracts.solicitudId": { $in: ids } }, { contracts: 1 }).lean();
console.log("ups", ups.length, Date.now() - t0, "ms", JSON.stringify(ups).length, "bytes");
console.log(JSON.stringify(await UserProject.find({ "contracts.solicitudId": { $in: ids } }).explain("executionStats")).match(/"totalDocsExamined":\d+|"executionTimeMillis":\d+|"stage":"IXSCAN"|"indexName":"[^"]+"/g));
const big = Object.entries(s[0]?.metadata || {}).map(([k, v]) => [k, JSON.stringify(v)?.length || 0]).sort((a: any, b: any) => b[1] - a[1]).slice(0, 5);
console.log("metadata más pesada", big);
await mongoose.disconnect();
